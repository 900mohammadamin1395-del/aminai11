def build_answer_message(riddle):

    if not riddle:
        return "چیستانی درکار نبود که جوابش رو بدم. بگو «یه چیستان بگو» تا شروع کنیم 🧩"

    return "💡 جواب: " + riddle["answer"] + "\n\nیه چیستان دیگه هم بخوای، فقط بگو «چیستان بعدی» 🧩"

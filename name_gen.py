def detect_request(message):

    text = message.strip()

    if "اسم" not in text:
        return False

    if any(word in text for word in TRIGGER_ACTION_WORDS):
        return True

    has_target = (
        any(word in text for word in GIRL_WORDS + BOY_WORDS + PET_WORDS)
        or "بچه" in text
    )

    wants_one = any(word in text for word in WANT_WORDS)

    return has_target and wants_one


def _pick_category(text):

    if any(word in text for word in PET_WORDS):
        return "pet"

    if any(word in text for word in GIRL_WORDS):
        return "girl"

    if any(word in text for word in BOY_WORDS):
        return "boy"

    return None


def build_answer(message):

    text = message.strip()

    category = _pick_category(text)

    if category == "pet":
        bank = PET_NAMES
        label = "حیوان خونگی"

    elif category == "girl":
        bank = GIRL_NAMES
        label = "دختر"

    elif category == "boy":
        bank = BOY_NAMES
        label = "پسر"

    else:
        # اگه مشخص نکرده بود دختر/پسر/حیوون خونگیه، از بین همه پیشنهاد بده
        bank = BOY_NAMES + GIRL_NAMES
        label = "پیشنهادی"

    picks = random.sample(bank, k=min(3, len(bank)))

    lines = ["👶 چند تا اسم " + label + " پیشنهاد می‌کنم:\n"]

    for name, meaning in picks:
        lines.append("• " + name + " — " + meaning)

    return "\n".join(lines)

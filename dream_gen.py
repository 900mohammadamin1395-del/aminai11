def detect_request(message):

    text = message.strip()

    return any(phrase in text for phrase in TRIGGER_PHRASES)


def find_symbol(message):

    text = message.strip()

    for symbol_name, data in SYMBOLS.items():

        for keyword in data["keywords"]:

            pattern = r"\b" + re.escape(keyword) + r"\b"

            if re.search(pattern, text):
                return symbol_name, data["meaning"]

    return None, None


def build_answer(message):

    symbol_name, meaning = find_symbol(message)

    if not meaning:

        examples = "، ".join(list(SYMBOLS.keys())[:10])

        return (
            "🌙 بگو تو خواب دقیقاً چی دیدی (مثلاً " + examples + " و...) تا تعبیرش رو برات بگم."
        )

    return "🌙 تعبیر خواب «" + symbol_name + "»:\n\n" + meaning
